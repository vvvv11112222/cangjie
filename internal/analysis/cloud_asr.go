type ASRSnapshot struct {
	BillingMode       string `json:"billing_mode,omitempty"`
	PriceSecondMicros int64  `json:"price_second_micros,omitempty"`
	APIBase           string `json:"api_base"`
	LanguageHints     string `json:"language_hints"`
	PriceVersion      string `json:"price_version"`
	InputPriceMicros  int64  `json:"input_price_micros"`
	OutputPriceMicros int64  `json:"output_price_micros"`
	MaxInputTokens    int64  `json:"max_input_tokens"`
	MaxOutputTokens   int64  `json:"max_output_tokens"`
	RequestVersion    string `json:"request_version"`
}

// Empty preserves historical token-billed snapshots and their interpretation.
func (c ASRSnapshot) secondsBilling() bool { return c.BillingMode == "seconds" }

func (c ASRSnapshot) ReserveMicros(durationMS int64) (int64, error) {
	if c.secondsBilling() {
		if durationMS <= 0 || durationMS > 40000 || c.PriceSecondMicros <= 0 || c.PriceSecondMicros > 1000000000 {
			return 0, fmt.Errorf("invalid duration-billed ASR reservation")
		}
		return ((durationMS + 999) / 1000) * c.PriceSecondMicros, nil
	}
	return tokenCostMicros(c.MaxInputTokens, c.MaxOutputTokens, c.InputPriceMicros, c.OutputPriceMicros)
}

type CloudASRConfig struct {
	Enabled bool
	APIKey  string
	ASRSnapshot
}

func (c CloudASRConfig) snapshot() *ASRSnapshot {
	if !c.Enabled {
		return nil
	}
	v := c.ASRSnapshot
	return &v
}

func LoadCloudASR(get func(string) string) (CloudASRConfig, error) {
	var c CloudASRConfig
	flag := get("ASR_CLOUD_ENABLED")
	if flag == "" || flag == "false" {
		return c, nil
	}
	if flag != "true" {
		return c, fmt.Errorf("ASR_CLOUD_ENABLED must be true or false")
	}
	c.Enabled = true
	c.APIKey = get("ASR_API_KEY")
	c.APIBase = strings.TrimRight(get("ASR_API_BASE"), "/")
	c.LanguageHints = get("ASR_LANGUAGE_HINTS")
	c.PriceVersion = get("ASR_PRICE_VERSION")
	c.BillingMode = get("ASR_BILLING_MODE")
	if c.BillingMode != "" && c.BillingMode != "tokens" && c.BillingMode != "seconds" {
		return c, fmt.Errorf("ASR_BILLING_MODE must be tokens or seconds")
	}
	c.RequestVersion = asrrequest.Version
	u, err := url.Parse(c.APIBase)
	if err != nil || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return c, fmt.Errorf("ASR_API_BASE is invalid")
	}
	local := u.Hostname() == "localhost" || (net.ParseIP(u.Hostname()) != nil && net.ParseIP(u.Hostname()).IsLoopback())
	if u.Scheme != "https" && !(u.Scheme == "http" && local) {
		return c, fmt.Errorf("ASR_API_BASE requires HTTPS except loopback tests")
	}
	if c.APIKey == "" || c.PriceVersion == "" || get("ASR_MODEL_NAME") == "" || get("ASR_MODEL_REVISION") == "" {
		return c, fmt.Errorf("cloud ASR requires key, model, revision and price version")
	}
	fields := map[string]*int64{"ASR_MAX_INPUT_TOKENS": &c.MaxInputTokens, "ASR_MAX_OUTPUT_TOKENS": &c.MaxOutputTokens}
	if c.secondsBilling() {
		fields["ASR_PRICE_PER_SECOND_MICROS"] = &c.PriceSecondMicros
	} else {
		fields["ASR_INPUT_PRICE_MICROS"] = &c.InputPriceMicros
		fields["ASR_OUTPUT_PRICE_MICROS"] = &c.OutputPriceMicros
	}
	for key, dest := range fields {
		v, e := strconv.ParseInt(get(key), 10, 64)
		if e != nil || v <= 0 || v > 1000000000 {
			return c, fmt.Errorf("%s must be a positive bounded integer", key)
		}
		*dest = v
	}
	if c.MaxInputTokens > 131072 || c.MaxOutputTokens > 4096 {
		return c, fmt.Errorf("ASR token limits exceed supported bounds")
	}
	return c, nil
}

type ASRChunk struct {
	StartMS   int64  `json:"start_ms"`
	EndMS     int64  `json:"end_ms"`
	WAVBase64 string `json:"wav_base64"`
}
type ASRText struct {
	Text string `json:"text_content"`
}

// Accept only bounded mono 16kHz PCM generated by the Worker; arbitrary URLs are never accepted.
func validateASRWAV(raw []byte, duration int64) error {
	if duration <= 0 || duration > 40000 || len(raw) < 44 || len(raw) > 1300000 || string(raw[:4]) != "RIFF" || string(raw[8:12]) != "WAVE" || uint64(binary.LittleEndian.Uint32(raw[4:8]))+8 != uint64(len(raw)) {
		return invalid("invalid ASR audio chunk")
	}
	formatOK := false
	dataBytes := -1
	for i := 12; i+8 <= len(raw); {
		n := int(binary.LittleEndian.Uint32(raw[i+4 : i+8]))
		end := i + 8 + n
		if end > len(raw) || n < 0 {
			return invalid("truncated WAV")
		}
		switch string(raw[i : i+4]) {
		case "fmt ":
			if formatOK || n < 16 {
				return invalid("invalid WAV format")
			}
			f := raw[i+8 : end]
			formatOK = binary.LittleEndian.Uint16(f) == 1 && binary.LittleEndian.Uint16(f[2:]) == 1 && binary.LittleEndian.Uint32(f[4:]) == 16000 && binary.LittleEndian.Uint32(f[8:]) == 32000 && binary.LittleEndian.Uint16(f[12:]) == 2 && binary.LittleEndian.Uint16(f[14:]) == 16
		case "data":
			if dataBytes >= 0 {
				return invalid("duplicate WAV data")
			}
			dataBytes = n
		}
		i = end + n%2
	}
	if !formatOK || dataBytes != int(duration)*32 {
		return invalid("WAV must match its millisecond interval at mono PCM16/16kHz")
	}
	return nil
}

func (s *Service) TranscribeChunk(ctx context.Context, jobID, token string, in ASRChunk) (ASRText, error) {
	empty := ASRText{}
	if !s.ModelConfig().CloudASR.Enabled {
		return empty, apperror.New(503, "SERVICE_UNAVAILABLE", "cloud ASR is not configured")
	}
	if in.StartMS < 0 || in.EndMS <= in.StartMS || in.EndMS-in.StartMS > 40000 {
		return empty, invalid("invalid chunk interval")
	}
	wav, err := base64.StdEncoding.DecodeString(in.WAVBase64)
	if err != nil {
		return empty, invalid("invalid WAV encoding")
	}
	if err = validateASRWAV(wav, in.EndMS-in.StartMS); err != nil {
		return empty, err
	}
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return empty, err
	}
	defer tx.Rollback(ctx)
	job, err := s.lockActiveJob(ctx, tx, jobID, token)
	if err != nil {
		return empty, err
	}
	if job.Stage != "audio_analysis" || job.Snapshot.CloudASR == nil {
		return empty, invalid("job does not enable cloud ASR")
	}
	c := *job.Snapshot.CloudASR
	if c.RequestVersion != asrrequest.Version || c.APIBase != s.ModelConfig().CloudASR.APIBase {
		return empty, state("ASR runtime differs from the fixed job configuration")
	}
	model := job.Snapshot.Executions["audio_analysis"].ASRModel
	if model == nil {
		return empty, invalid("job has no ASR model")
	}
	duration, err := s.mediaDuration(ctx, tx, job.MediaID)
	if err != nil {
		return empty, err
	}
	if in.EndMS > duration {
		return empty, invalid("chunk exceeds source duration")
	}
	j := goJob{ID: jobID, RunID: job.RunID, SessionID: job.SessionID, MediaID: job.MediaID, Stage: job.Stage, Token: token}
	if err = s.lockReportDispatch(ctx, tx, j); err != nil {
		return empty, apperror.New(403, "EXTERNAL_PROCESSING_FORBIDDEN", "source or job no longer permits external processing")
	}
	body := asrrequest.Body(wav, model.Name, c.LanguageHints)
	if !c.secondsBilling() {
		body["max_tokens"] = c.MaxOutputTokens
	}
	raw, _ := json.Marshal(body)
	sha := digestBytes(raw)
	key := fmt.Sprintf("asr:%s:%d:%d", jobID, in.StartMS, in.EndMS)
	artifact := fmt.Sprintf("__asr/%d/%d", in.StartMS, in.EndMS)
	var cached []byte
	err = tx.QueryRow(ctx, `SELECT metadata FROM teaching.job_artifacts WHERE job_id=$1 AND artifact_key=$2`, jobID, artifact).Scan(&cached)
	if err == nil {
		var v struct {
			SHA  string `json:"request_sha256"`
			Text string `json:"text_content"`
		}
		if e := json.Unmarshal(cached, &v); e != nil {
			return empty, e
		}
		if v.SHA != sha {
			return empty, state("ASR replay changed audio content")
		}
		return ASRText{v.Text}, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return empty, err
	}
	var blocked bool
	if err = tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM teaching.model_calls WHERE call_key=$1 OR (job_id=$2 AND status IN('reserved','unknown')))`, key, jobID).Scan(&blocked); err != nil {
		return empty, err
	}
	if blocked {
		return empty, state("ASR request already dispatched; reconcile uncertain billing before a new analysis")
	}
	var priorEnd int64
	if err = tx.QueryRow(ctx, `SELECT COALESCE(max((metadata->>'end_ms')::bigint),0) FROM teaching.job_artifacts WHERE job_id=$1 AND artifact_key LIKE '__asr/%'`, jobID).Scan(&priorEnd); err != nil {
		return empty, err
	}
	if in.StartMS != priorEnd {
		return empty, invalid("ASR chunks must be contiguous and ordered")
	}
	reserve, err := c.ReserveMicros(in.EndMS - in.StartMS)
	if err != nil {
		return empty, err
	}
	period := billingPeriod(time.Now(), s.cfg.ReportBudgetTimezone)
	currency := s.cfg.ReportBudgetCurrency
	if _, err = tx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1,0))`, currency+":"+period); err != nil {
		return empty, err
	}
	var used int64
	if err = tx.QueryRow(ctx, `SELECT COALESCE(round(sum(CASE WHEN status IN('reserved','unknown') THEN reserved_cost ELSE actual_cost END)*1000000),0)::bigint FROM teaching.model_calls WHERE currency=$1 AND billing_period=$2::date`, currency, period).Scan(&used); err != nil {
		return empty, err
	}
	if err = tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM teaching.model_calls WHERE currency=$1 AND billing_period=$2::date AND actual_cost>reserved_cost AND reconciled_by IS NULL)`, currency, period).Scan(&blocked); err != nil {
		return empty, err
	}
	if blocked || reserve <= 0 || s.ModelConfig().ReportMonthlyBudgetMicros <= 0 || used > s.ModelConfig().ReportMonthlyBudgetMicros-reserve {
		return empty, apperror.New(409, "BUDGET_EXHAUSTED", "ASR budget exhausted or reconciliation required")
	}
	_, err = tx.Exec(ctx, `INSERT INTO teaching.model_calls(run_id,job_id,call_key,provider,model_name,prompt_version,status,currency,reserved_cost,billing_period,price_version,request_sha256,dispatch_started_at) VALUES($1,$2,$3,'openai-compatible-asr',$4,$5,'reserved',$6,$7::numeric/1000000,$8::date,$9,$10,now())`, job.RunID, jobID, key, model.Name, asrrequest.Version, currency, reserve, period, c.PriceVersion, sha)
	if err != nil {
		return empty, err
	}
	if err = tx.Commit(ctx); err != nil {
		return empty, err
	}
	// A client disconnect must not erase billing state. No automatic provider retry.
	callCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 180*time.Second)
	defer cancel()
	result, usage, callErr := s.callASRBilled(callCtx, c.APIBase, raw, c.secondsBilling())
	settleCtx, done := context.WithTimeout(context.Background(), 15*time.Second)
	defer done()
	if !usage.UsageKnown {
		_, _ = s.pool.Exec(settleCtx, `UPDATE teaching.model_calls SET status='unknown',lock_version=lock_version+1 WHERE call_key=$1 AND status='reserved'`, key)
		return empty, apperror.New(409, "MODEL_CALL_UNKNOWN", "ASR outcome or billing is unknown; no automatic repeat")
	}
	cost, e := tokenCostMicros(usage.InputTokens, usage.OutputTokens, c.InputPriceMicros, c.OutputPriceMicros)
	if c.secondsBilling() {
		cost = usage.BilledSeconds * c.PriceSecondMicros
		e = nil
	}
	if e != nil {
		return empty, e
	}
	tx, err = s.pool.Begin(settleCtx)
	if err != nil {
		return empty, err
	}
	defer tx.Rollback(settleCtx)
	if _, err = tx.Exec(settleCtx, `SELECT pg_advisory_xact_lock(hashtextextended($1,0))`, currency+":"+period); err != nil {
		return empty, err
	}
	status := "succeeded"
	if callErr != nil {
		status = "failed"
	}
	var inputTokens, outputTokens any = usage.InputTokens, usage.OutputTokens
	if c.secondsBilling() && !usage.TokensKnown {
		inputTokens, outputTokens = nil, nil
	}
	tag, err := tx.Exec(settleCtx, `UPDATE teaching.model_calls SET status=$2,actual_cost=$3::numeric/1000000,input_tokens=$4,output_tokens=$5,provider_request_id=NULLIF($6,''),settled_at=now(),lock_version=lock_version+1 WHERE call_key=$1 AND status IN('reserved','unknown') AND reconciled_by IS NULL`, key, status, cost, inputTokens, outputTokens, usage.ProviderRequestID)
	if err != nil {
		return empty, err
	}
	if tag.RowsAffected() != 1 {
		return empty, state("ASR bill was reconciled while provider request was running")
	}
	if c.secondsBilling() {
		// Keep exact billed units outside classroom content, including after its
		// eventual cleanup. Never reinterpret seconds as input/output tokens.
		if _, err = tx.Exec(settleCtx, `INSERT INTO teaching.audit_logs(action,resource_type,resource_id,result,request_id,metadata)
			VALUES('model.asr.settle','analysis_run',$1,'success','asr-billing',jsonb_build_object('billing_mode','seconds','billed_seconds',$2::bigint,'price_second_micros',$3::bigint,'price_version',$4::text,'call_key',$5::text))`, job.RunID, usage.BilledSeconds, c.PriceSecondMicros, c.PriceVersion, key); err != nil {
			return empty, err
		}
	}
	if err = tx.Commit(settleCtx); err != nil {
		return empty, err
	}
	if callErr != nil {
		return empty, apperror.New(422, "INVALID_RESULT", "ASR provider returned invalid text")
	}
	tx, err = s.pool.Begin(settleCtx)
	if err != nil {
		return empty, err
	}
	defer tx.Rollback(settleCtx)
	active, err := s.lockReportResultAcceptance(settleCtx, tx, j)
	if err != nil {
		return empty, err
	}
	if !active || time.Now().After(job.Deadline) {
		return empty, leaseLost()
	}
	metadata := map[string]any{"request_sha256": sha, "text_content": result.Text, "start_ms": in.StartMS, "end_ms": in.EndMS}
	_, err = tx.Exec(settleCtx, `INSERT INTO teaching.job_artifacts(job_id,run_id,session_id,lease_token,artifact_key,metadata) VALUES($1,$2,$3,$4,$5,$6)`, jobID, job.RunID, job.SessionID, token, artifact, metadata)
	if err != nil {
		return empty, err
	}
	if err = tx.Commit(settleCtx); err != nil {
		return empty, err
	}
	return result, nil
}

func (s *Service) callASR(ctx context.Context, base string, raw []byte) (ASRText, modelCallResult, error) {
	return s.callASRBilled(ctx, base, raw, false)
}

func (s *Service) callASRBilled(ctx context.Context, base string, raw []byte, secondsBilling bool) (ASRText, modelCallResult, error) {
	var text ASRText
	var result modelCallResult
	req, err := http.NewRequestWithContext(ctx, "POST", base+"/chat/completions", bytes.NewReader(raw))
	if err != nil {
		return text, result, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+s.ModelConfig().CloudASR.APIKey)
	client := &http.Client{CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}
	resp, err := client.Do(req)
	if err != nil {
		return text, result, err
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return text, result, err
	}
	var envelope struct {
		ID      string          `json:"id"`
		Usage   json.RawMessage `json:"usage"`
		Choices json.RawMessage `json:"choices"`
	}
	if err = json.Unmarshal(data, &envelope); err != nil {
		return text, result, err
	}
	result.ProviderRequestID = envelope.ID
	var usage struct {
		Input   *int64 `json:"prompt_tokens"`
		Output  *int64 `json:"completion_tokens"`
		Seconds *int64 `json:"seconds"`
	}
	if json.Unmarshal(envelope.Usage, &usage) == nil && usage.Input != nil && usage.Output != nil && *usage.Input >= 0 && *usage.Output >= 0 {
		result.UsageKnown = true
		result.TokensKnown = true
		result.InputTokens = *usage.Input
		result.OutputTokens = *usage.Output
	}
	if secondsBilling {
		// Each request contains at most 40 seconds of verified PCM. Other values
		// need reconciliation, not a guessed conversion from tokens.
		result.UsageKnown = usage.Seconds != nil && *usage.Seconds > 0 && *usage.Seconds <= 40
		if result.UsageKnown {
			result.BilledSeconds = *usage.Seconds
		}
	}
	var choices []struct {
		Finish  string `json:"finish_reason"`
		Message struct {
			Content *string `json:"content"`
		} `json:"message"`
	}
	if resp.StatusCode != 200 || json.Unmarshal(envelope.Choices, &choices) != nil || len(choices) != 1 || choices[0].Finish != "stop" || choices[0].Message.Content == nil {
		return text, result, fmt.Errorf("invalid ASR response")
	}
	text.Text = strings.TrimSpace(*choices[0].Message.Content)
	if utf8.RuneCountInString(text.Text) > 4000 {
		return ASRText{}, result, fmt.Errorf("ASR chunk text exceeds contract bound")
	}
	return text, result, nil
}

// The main transcription must be the exact sequence accepted from the provider.
// A lease retry may read the same immutable cached chunks, but cannot invent text.
func validateCloudAudioResult(ctx context.Context, tx pgx.Tx, jobID string, audio AudioResult) error {
	rows, err := tx.Query(ctx, `SELECT metadata FROM teaching.job_artifacts WHERE job_id=$1 AND artifact_key LIKE '__asr/%' ORDER BY (metadata->>'start_ms')::bigint`, jobID)
	if err != nil {
		return err
	}
	defer rows.Close()
	expected := []Segment{}
	end := int64(0)
	for rows.Next() {
		var raw []byte
		if err := rows.Scan(&raw); err != nil {
			return err
		}
		var chunk struct {
			Start int64  `json:"start_ms"`
			End   int64  `json:"end_ms"`
			Text  string `json:"text_content"`
		}
		if err := json.Unmarshal(raw, &chunk); err != nil {
			return err
		}
		if chunk.Start != end || chunk.End <= chunk.Start {
			return invalidResult("cached ASR timeline is invalid")
		}
		end = chunk.End
		if chunk.Text != "" {
			expected = append(expected, Segment{SegmentNo: len(expected), StartMS: chunk.Start, EndMS: chunk.End, Text: chunk.Text, Speaker: "unknown"})
		}
	}
	if err := rows.Err(); err != nil {
		return err
	}
	if end == 0 || len(audio.Coverage) != 1 || audio.Coverage[0].StartMS != 0 || audio.Coverage[0].EndMS != end || audio.AudioAssetID != nil || len(audio.Segments) != len(expected) {
		return invalidResult("audio result differs from accepted cloud ASR chunks")
	}
	for i := range expected {
		if audio.Segments[i] != expected[i] {
			return invalidResult("audio transcript differs from accepted cloud ASR text")
		}
	}
	return nil
}
